-- PostgreSQL only. Explicit initialization; no data migration or authentication.
-- Separate from public so Supabase Data API does not expose leads by default.
CREATE SCHEMA IF NOT EXISTS business;
CREATE TABLE IF NOT EXISTS business.leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    note TEXT NOT NULL,
    legacy_sqlite_id BIGINT UNIQUE,
    legacy_duckdb_id BIGINT UNIQUE
);
REVOKE ALL ON SCHEMA business FROM PUBLIC;
REVOKE ALL ON business.leads FROM PUBLIC;
