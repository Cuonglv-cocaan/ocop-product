-- One row per customer question, completed in place when the AI responds.
CREATE TABLE business.chat_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES business.chat_conversations(id),
    turn_number INTEGER NOT NULL CHECK (turn_number > 0),
    question TEXT NOT NULL,
    answer TEXT,
    products JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(products) = 'array'),
    status TEXT NOT NULL CHECK (status IN ('pending', 'answered', 'error')),
    asked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    answered_at TIMESTAMPTZ,
    UNIQUE (conversation_id, turn_number)
);
REVOKE ALL ON business.chat_turns FROM PUBLIC;
CREATE INDEX chat_turns_asked_idx ON business.chat_turns(asked_at);

-- Preserve legacy snapshots as a backup. Their per-message times were not recorded:
-- use the conversation timestamps for backfilled rows only.
INSERT INTO business.chat_turns
    (conversation_id,turn_number,question,answer,products,status,asked_at,answered_at)
SELECT c.id, q.turn_number, q.message->>'content', a.message->>'content',
    COALESCE(a.message->'products', '[]'::jsonb),
    CASE WHEN a.message IS NULL THEN 'pending'
         WHEN a.message->>'error' = 'true' THEN 'error' ELSE 'answered' END,
    c.created_at, CASE WHEN a.message IS NOT NULL THEN c.updated_at END
FROM business.chat_conversations c
CROSS JOIN LATERAL (
    SELECT message, position,
        row_number() OVER (ORDER BY position)::INTEGER AS turn_number,
        lead(position) OVER (ORDER BY position) AS next_position
    FROM jsonb_array_elements(c.messages) WITH ORDINALITY AS m(message,position)
    WHERE message->>'role' = 'user'
) q
LEFT JOIN LATERAL (
    SELECT message FROM jsonb_array_elements(c.messages) WITH ORDINALITY AS m(message,position)
    WHERE position > q.position AND (q.next_position IS NULL OR position < q.next_position)
        AND message->>'role' = 'assistant'
    ORDER BY position LIMIT 1
) a ON TRUE;

-- Convenient research view: no need to join account/session metadata manually.
CREATE VIEW business.chat_research AS
SELECT t.*, c.user_id, c.session_key, c.title AS conversation_title
FROM business.chat_turns t
JOIN business.chat_conversations c ON c.id=t.conversation_id;
REVOKE ALL ON business.chat_research FROM PUBLIC;
